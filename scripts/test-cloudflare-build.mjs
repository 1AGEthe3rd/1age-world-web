import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {createHash} from 'node:crypto';
const m=JSON.parse(readFileSync('dist/engine-manifest.json','utf8'));
const original=readFileSync('index.wasm'),gzip=readFileSync('dist/'+m.file);
assert.equal(original.length,m.rawBytes);assert.ok(gzip.length<=25*1024*1024);assert.ok(!existsSync('dist/index.wasm'));
assert.equal(createHash('sha256').update(original).digest('hex'),m.sha256);
const calls=[];
const window={fetch:async(input)=>{calls.push(String(input));return String(input).endsWith(m.file)?new Response(gzip):new Response('normal')}};
const context={window,document:{baseURI:'https://example.pages.dev/'},URL,Request,Response,DecompressionStream};
runInNewContext(readFileSync('dist/world-engine-loader.js','utf8'),context);
const wasm=await window.fetch('index.wasm');
assert.equal(wasm.headers.get('content-type'),'application/wasm');
assert.equal(wasm.headers.get('content-length'),String(original.length));
const restored=Buffer.from(await wasm.arrayBuffer());assert.deepEqual(restored,original);
assert.ok(WebAssembly.validate(restored),'Restored engine must validate as WebAssembly');
assert.equal(await (await window.fetch('index.pck')).text(),'normal');
assert.equal(await (await window.fetch('https://external.test/index.wasm')).text(),'normal');
assert.equal(calls.length,3);
assert.deepEqual(readFileSync('dist/index.pck'),readFileSync('index.pck'));
assert.deepEqual(readFileSync('dist/index.js'),readFileSync('index.js'));
assert.ok(readFileSync('dist/index.html','utf8').indexOf('world-engine-loader.js')<readFileSync('dist/index.html','utf8').indexOf('src="index.js"'));
console.log('Cloudflare output and actual restored engine verified.');
